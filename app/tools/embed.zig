const std = @import("std");
const Io = std.Io;

pub fn main(init: std.process.Init) !void {
    const io = init.io;
    const arena = init.arena.allocator();

    const args = try init.minimal.args.toSlice(arena);
    if (args.len != 3) {
        std.debug.print("usage: {s} <input dir> <output dir>\n", .{args[0]});
        std.process.exit(2);
    }

    const cwd = Io.Dir.cwd();
    var input = try cwd.openDir(io, args[1], .{ .iterate = true });
    defer input.close(io);
    var output = try cwd.createDirPathOpen(io, args[2], .{});
    defer output.close(io);

    var paths: std.ArrayList([]const u8) = .empty;
    var walker = try input.walk(arena);
    defer walker.deinit();
    while (try walker.next(io)) |entry| {
        if (entry.kind != .file) continue;
        try paths.append(arena, try arena.dupe(u8, entry.path));
    }
    std.mem.sort([]const u8, paths.items, {}, struct {
        fn lessThan(_: void, a: []const u8, b: []const u8) bool {
            return std.mem.lessThan(u8, a, b);
        }
    }.lessThan);

    var source: Io.Writer.Allocating = .init(arena);
    const w = &source.writer;
    try w.writeAll(
        \\//! Generated by tools/embed.zig. Do not edit.
        \\
        \\pub const File = struct { path: []const u8, response: []const u8 };
        \\
        \\pub const files = [_]File{
        \\
    );
    for (paths.items, 0..) |path, index| {
        const copy = try std.fmt.allocPrint(arena, "files/{d}", .{index});
        try input.copyFile(path, output, copy, io, .{ .make_path = true });
        try w.print("    .{{ .path = \"/{f}\", .response = response(\"{s}\", \"{s}\", @embedFile(\"{s}\")) }},\n", .{
            std.zig.fmtString(path), mimeType(path), cacheControl(path), copy,
        });
    }
    try w.writeAll(
        \\};
        \\
        \\fn response(comptime mime: []const u8, comptime cache: []const u8, comptime body: []const u8) []const u8 {
        \\    @setEvalBranchQuota(10_000);
        \\    return "HTTP/1.1 200 OK\r\nContent-Type: " ++ mime ++
        \\        "\r\nCache-Control: " ++ cache ++
        \\        "\r\nContent-Length: " ++ @import("std").fmt.comptimePrint("{d}", .{body.len}) ++
        \\        "\r\nConnection: close\r\n\r\n" ++ body;
        \\}
        \\
    );

    try output.writeFile(io, .{ .sub_path = "assets.zig", .data = source.written() });
}

fn cacheControl(path: []const u8) []const u8 {
    return if (std.mem.startsWith(u8, path, "assets/")) "public, max-age=31536000, immutable" else "no-cache";
}

fn mimeType(path: []const u8) []const u8 {
    const types = [_]struct { []const u8, []const u8 }{
        .{ ".html", "text/html; charset=utf-8" },
        .{ ".js", "text/javascript; charset=utf-8" },
        .{ ".mjs", "text/javascript; charset=utf-8" },
        .{ ".css", "text/css; charset=utf-8" },
        .{ ".json", "application/json" },
        .{ ".map", "application/json" },
        .{ ".svg", "image/svg+xml" },
        .{ ".png", "image/png" },
        .{ ".jpg", "image/jpeg" },
        .{ ".jpeg", "image/jpeg" },
        .{ ".gif", "image/gif" },
        .{ ".webp", "image/webp" },
        .{ ".ico", "image/x-icon" },
        .{ ".woff", "font/woff" },
        .{ ".woff2", "font/woff2" },
        .{ ".ttf", "font/ttf" },
        .{ ".wasm", "application/wasm" },
        .{ ".txt", "text/plain; charset=utf-8" },
    };
    const ext = std.fs.path.extension(path);
    for (types) |entry| {
        if (std.ascii.eqlIgnoreCase(ext, entry[0])) return entry[1];
    }
    return "application/octet-stream";
}
