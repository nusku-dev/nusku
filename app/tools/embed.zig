//! Build-time tool: embeds a directory of web assets in the app.
//!
//! Usage: embed <input dir> <output dir>
//!
//! Writes, for every file under the input, `<output>/files/<n>`: a complete HTTP response, the
//! headers and then the file. `<output>/assets.zig` lists them with `@embedFile`. The app hands
//! these straight to WebUI's file handler, with no copying or I/O at run time.
//!
//! The headers are added here, not with `++` at compile time: comptime concatenation keeps
//! every byte as a separate value, and on a bundle of a megabyte or so that took gigabytes of
//! compiler memory. `@embedFile` alone is a plain copy.

const std = @import("std");
const Io = std.Io;

pub fn main(init: std.process.Init) !void {
    const io = init.io;
    const arena = init.arena.allocator();

    const args = try init.minimal.args.toSlice(arena);
    if (args.len != 3) {
        std.debug.print("usage: {s} <input dir> <output dir>\n", .{args[0]});
        std.process.exit(2);
    }

    const cwd = Io.Dir.cwd();
    var input = try cwd.openDir(io, args[1], .{ .iterate = true });
    defer input.close(io);
    var output = try cwd.createDirPathOpen(io, args[2], .{});
    defer output.close(io);

    var paths: std.ArrayList([]const u8) = .empty;
    var walker = try input.walk(arena);
    defer walker.deinit();
    while (try walker.next(io)) |entry| {
        if (entry.kind != .file) continue;
        try paths.append(arena, try arena.dupe(u8, entry.path));
    }
    std.mem.sort([]const u8, paths.items, {}, struct {
        fn lessThan(_: void, a: []const u8, b: []const u8) bool {
            return std.mem.lessThan(u8, a, b);
        }
    }.lessThan);

    var source: Io.Writer.Allocating = .init(arena);
    const w = &source.writer;
    try w.writeAll(
        \\//! Generated by tools/embed.zig. Do not edit.
        \\
        \\pub const File = struct { path: []const u8, response: []const u8 };
        \\
        \\pub const files = [_]File{
        \\
    );
    try output.createDirPath(io, "files");
    for (paths.items, 0..) |path, index| {
        const body = try input.readFileAlloc(io, path, arena, .limited(64 << 20));
        const response = try std.fmt.allocPrint(
            arena,
            "HTTP/1.1 200 OK\r\nContent-Type: {s}\r\nCache-Control: {s}\r\nContent-Length: {d}\r\nConnection: close\r\n\r\n",
            .{ mimeType(path), cacheControl(path), body.len },
        );
        const name = try std.fmt.allocPrint(arena, "files/{d}", .{index});
        const file = try output.createFile(io, name, .{});
        defer file.close(io);
        var buffer: [64 * 1024]u8 = undefined;
        var writer = file.writer(io, &buffer);
        try writer.interface.writeAll(response);
        try writer.interface.writeAll(body);
        try writer.interface.flush();
        try w.print("    .{{ .path = \"/{f}\", .response = @embedFile(\"{s}\") }},\n", .{ std.zig.fmtString(path), name });
    }
    try w.writeAll("};\n");

    try output.writeFile(io, .{ .sub_path = "assets.zig", .data = source.written() });
}

/// Vite puts a content hash in every file name under `assets/`, so those never change and can be
/// cached forever. Everything else (index.html above all) must be checked each time.
fn cacheControl(path: []const u8) []const u8 {
    return if (std.mem.startsWith(u8, path, "assets/")) "public, max-age=31536000, immutable" else "no-cache";
}

fn mimeType(path: []const u8) []const u8 {
    const types = [_]struct { []const u8, []const u8 }{
        .{ ".html", "text/html; charset=utf-8" },
        .{ ".js", "text/javascript; charset=utf-8" },
        .{ ".mjs", "text/javascript; charset=utf-8" },
        .{ ".css", "text/css; charset=utf-8" },
        .{ ".json", "application/json" },
        .{ ".map", "application/json" },
        .{ ".svg", "image/svg+xml" },
        .{ ".png", "image/png" },
        .{ ".jpg", "image/jpeg" },
        .{ ".jpeg", "image/jpeg" },
        .{ ".gif", "image/gif" },
        .{ ".webp", "image/webp" },
        .{ ".ico", "image/x-icon" },
        .{ ".woff", "font/woff" },
        .{ ".woff2", "font/woff2" },
        .{ ".ttf", "font/ttf" },
        .{ ".wasm", "application/wasm" },
        .{ ".txt", "text/plain; charset=utf-8" },
    };
    const ext = std.fs.path.extension(path);
    for (types) |entry| {
        if (std.ascii.eqlIgnoreCase(ext, entry[0])) return entry[1];
    }
    return "application/octet-stream";
}
